// scripts/extract_items.go
//
// 从样本抽取物品名 → 生成 seeds/items_v1.sql。
// canonical_id = "item_" + sha1(name_zh)[:10]
// category 用样本里的"段落"序号（同一空行段相邻的物品归为一组），admin 可后续编辑。
//
// 用法：
//   go run scripts/extract_items.go -in 样本.txt -out internal/store/seeds/0001_items.sql

//go:build ignore

package main

import (
	"crypto/sha1"
	"encoding/hex"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
)

const crateSuffix = " (箱装)"

// 段落 → 默认 category 名（人工归类的猜测，admin 可改）。
var sectionGuess = []string{
	"小型武器",
	"载具",
	"通用载具",
	"大型武器",
	"建筑/部件",
	"装甲建筑",
}

func main() {
	in := flag.String("in", "样本.txt", "input txt")
	out := flag.String("out", "internal/store/seeds/0001_items.sql", "output sql")
	flag.Parse()

	raw, err := os.ReadFile(*in)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	text := strings.ReplaceAll(string(raw), "\r\n", "\n")
	text = strings.ReplaceAll(text, "\r", "\n")

	lines := strings.Split(text, "\n")

	type itemKey string
	type itemMeta struct {
		section int
		first   bool // 第一次出现是散件还是箱装（仅参考）
	}
	items := map[itemKey]*itemMeta{}

	section := 0
	for i, ln := range lines {
		if i == 0 {
			continue // header
		}
		if strings.TrimSpace(ln) == "" {
			section++
			continue
		}
		commaIdx := strings.LastIndex(ln, ",")
		if commaIdx < 0 {
			continue
		}
		name := ln[:commaIdx]
		name = strings.TrimSuffix(name, crateSuffix)
		if _, ok := items[itemKey(name)]; !ok {
			items[itemKey(name)] = &itemMeta{section: section, first: !strings.HasSuffix(ln[:commaIdx], crateSuffix)}
		}
	}

	names := make([]string, 0, len(items))
	for k := range items {
		names = append(names, string(k))
	}
	sort.Strings(names)

	var sb strings.Builder
	sb.WriteString("-- generated by scripts/extract_items.go from sample (do not hand-edit)\n")
	sb.WriteString("-- 后续游戏更新引入新物品，由 owner 在 /admin 里追加。\n\n")
	sb.WriteString("BEGIN;\n")
	for _, n := range names {
		meta := items[itemKey(n)]
		cid := makeID(n)
		cat := guessCategory(meta.section)
		sb.WriteString(fmt.Sprintf(
			"INSERT OR IGNORE INTO items (canonical_id, name_zh, category, icon_source, updated_at) VALUES (%s, %s, %s, 'placeholder', strftime('%%s','now'));\n",
			sqlStr(cid), sqlStr(n), sqlStr(cat),
		))
		sb.WriteString(fmt.Sprintf(
			"INSERT OR IGNORE INTO item_aliases (alias, canonical_id) VALUES (%s, %s);\n",
			sqlStr(n), sqlStr(cid),
		))
	}
	sb.WriteString("COMMIT;\n")

	if err := os.WriteFile(*out, []byte(sb.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %d items to %s\n", len(names), *out)
}

func makeID(name string) string {
	h := sha1.Sum([]byte(name))
	return "item_" + hex.EncodeToString(h[:])[:10]
}

func guessCategory(section int) string {
	if section < 0 || section >= len(sectionGuess) {
		return "其他"
	}
	return sectionGuess[section]
}

func sqlStr(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}